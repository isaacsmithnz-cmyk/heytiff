"""Every workflow, today and in the new layout.

A step is a string. A step starting with "~" is typing or picking (a field),
anything else is a press. Paths are (label, [steps]). The first step of the
first new path is the first press.

Today's paths come from the code on main (0c50efd), traced by five read-only
agents; labels are the words the app renders.
"""


def W(id, title, who, today, new, tdoors=0, tnote="", ndoors="", nnote="", say=""):
    return dict(id=id, title=title, who=who, today=today, new=new, tdoors=tdoors,
                tnote=tnote, ndoors=ndoors, nnote=nnote, say=say)


