/* An id a browser mints for one press — a reply box, the diary's pen, a
   Mark done — so pressing it twice is still ONE thing (two-way phase 2).
   The server takes it only uuid-shaped, so the fallback is one too:
   randomUUID needs a secure context, and a plain-http dev host must keep
   working rather than throwing inside a keystroke. Pure. */

export function mintPressId(): string {
  const c = globalThis.crypto;
  if (c && typeof c.randomUUID === "function") return c.randomUUID();
  const b = new Uint8Array(16);
  if (c && typeof c.getRandomValues === "function") c.getRandomValues(b);
  else for (let i = 0; i < b.length; i++) b[i] = Math.floor(Math.random() * 256);
  b[6] = (b[6] & 0x0f) | 0x40;
  b[8] = (b[8] & 0x3f) | 0x80;
  const h = Array.from(b, (x) => x.toString(16).padStart(2, "0")).join("");
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-${h.slice(12, 16)}-${h.slice(16, 20)}-${h.slice(20)}`;
}
